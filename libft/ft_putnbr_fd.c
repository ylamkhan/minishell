#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	l;

	l = (long)n;
	if (l < 0)
	{
		ft_putchar_fd('-', fd);
		l *= -1;
	}
	if (l >= 10)
	{
		ft_putnbr_fd(l / 10, fd);
		l %= 10;
	}
	if (l < 10)
		ft_putchar_fd(l + '0', fd);
}
